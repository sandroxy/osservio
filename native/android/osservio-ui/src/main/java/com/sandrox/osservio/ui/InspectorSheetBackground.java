package com.sandrox.osservio.ui;

import android.content.Context;
import android.graphics.Canvas;
import android.graphics.Color;
import android.graphics.LinearGradient;
import android.graphics.Paint;
import android.graphics.Path;
import android.graphics.RadialGradient;
import android.graphics.Rect;
import android.graphics.RectF;
import android.graphics.Shader;
import android.graphics.drawable.GradientDrawable;

/** Opaque sheet with a palette-colored upper edge in dark appearance. */
final class InspectorSheetBackground extends GradientDrawable {
    private final float density, radius;
    private final int lightColor;
    private final boolean dark;
    private final Paint glow = new Paint(Paint.ANTI_ALIAS_FLAG);
    private final Paint leftLight = new Paint(Paint.ANTI_ALIAS_FLAG);
    private final Paint rightLight = new Paint(Paint.ANTI_ALIAS_FLAG);
    private final Paint rimLight = new Paint(Paint.ANTI_ALIAS_FLAG);
    private final Path outline = new Path(), rim = new Path();
    private float glowBottom;

    InspectorSheetBackground(Context context) {
        density = context.getResources().getDisplayMetrics().density;
        radius = InspectorTheme.dp(context, 24);
        lightColor = InspectorPreferences.palette(context).dark;
        dark = (context.getResources().getConfiguration().uiMode & android.content.res.Configuration.UI_MODE_NIGHT_MASK)
            == android.content.res.Configuration.UI_MODE_NIGHT_YES;
        setColor(InspectorTheme.canvas(context));
        setCornerRadii(new float[] {radius, radius, radius, radius, 0, 0, 0, 0});
        rimLight.setStyle(Paint.Style.STROKE);
        rimLight.setStrokeWidth(density * 0.65f);
    }

    @Override protected void onBoundsChange(Rect bounds) {
        super.onBoundsChange(bounds);
        outline.rewind(); rim.rewind();
        if (!dark || bounds.isEmpty()) return;
        float r = Math.min(radius, Math.min(bounds.width(), bounds.height()) / 2f);
        glowBottom = Math.min(bounds.bottom, bounds.top + 44 * density);
        outline.addRoundRect(new RectF(bounds), new float[] {r, r, r, r, 0, 0, 0, 0}, Path.Direction.CW);

        // These gradients are recorded with the background, not regenerated by touch or time.
        glow.setShader(new LinearGradient(0, bounds.top, 0, glowBottom,
            new int[] {tint(lightColor, 76), tint(lightColor, 52), tint(lightColor, 18), tint(lightColor, 0)},
            new float[] {0, 0.14f, 0.48f, 1}, Shader.TileMode.CLAMP));
        int[] cornerColors = {tint(lightColor, 52), tint(lightColor, 14), tint(lightColor, 0)};
        float[] cornerStops = {0, 0.5f, 1};
        leftLight.setShader(new RadialGradient(bounds.left + r, bounds.top + density * 2, 48 * density,
            cornerColors, cornerStops, Shader.TileMode.CLAMP));
        rightLight.setShader(new RadialGradient(bounds.right - r, bounds.top + density * 2, 48 * density,
            cornerColors, cornerStops, Shader.TileMode.CLAMP));

        float inset = Math.min(density * 0.5f, r / 2);
        rim.moveTo(bounds.left + inset, glowBottom);
        rim.lineTo(bounds.left + inset, bounds.top + r);
        rim.arcTo(bounds.left + inset, bounds.top + inset, bounds.left + r * 2 - inset, bounds.top + r * 2 - inset, 180, 90, false);
        rim.lineTo(bounds.right - r, bounds.top + inset);
        rim.arcTo(bounds.right - r * 2 + inset, bounds.top + inset, bounds.right - inset, bounds.top + r * 2 - inset, 270, 90, false);
        rim.lineTo(bounds.right - inset, glowBottom);
        int highlight = Color.rgb((Color.red(lightColor) + 255) / 2,
            (Color.green(lightColor) + 255) / 2, (Color.blue(lightColor) + 255) / 2);
        rimLight.setShader(new LinearGradient(0, bounds.top, 0, glowBottom,
            new int[] {tint(highlight, 150), tint(highlight, 44), tint(highlight, 0)},
            new float[] {0, 0.4f, 1}, Shader.TileMode.CLAMP));
    }

    @Override public void draw(Canvas canvas) {
        super.draw(canvas);
        Rect bounds = getBounds();
        if (!dark || bounds.isEmpty()) return;
        int save = canvas.save();
        canvas.clipPath(outline);
        drawGlow(canvas, glow, bounds.left, bounds.right);
        drawGlow(canvas, leftLight, bounds.left, Math.min(bounds.right, bounds.left + radius + 48 * density));
        drawGlow(canvas, rightLight, Math.max(bounds.left, bounds.right - radius - 48 * density), bounds.right);
        rimLight.setAlpha(getAlpha()); rimLight.setColorFilter(getColorFilter());
        canvas.drawPath(rim, rimLight);
        canvas.restoreToCount(save);
    }

    private void drawGlow(Canvas canvas, Paint paint, float left, float right) {
        paint.setAlpha(getAlpha()); paint.setColorFilter(getColorFilter());
        canvas.drawRect(left, getBounds().top, right, glowBottom, paint);
    }
    private static int tint(int color, int alpha) { return (color & 0x00FFFFFF) | (alpha << 24); }
}
