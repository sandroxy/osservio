import Foundation

/// Explicit values only: capture never reflects arbitrary objects or calls their descriptions.
public indirect enum LogValue: Sendable {
    case null, boolean(Bool), integer(Int64), number(Double), string(String)
    case array([LogValue]), object([LogField])
}

/// Ordered fields preserve duplicate names, just as the JSON reader preserves duplicate keys.
public struct LogField: Sendable {
    public let name: String
    public let value: LogValue
    public init(_ name: String, _ value: LogValue) { self.name = name; self.value = value }
}

public struct LogCallSite: Sendable {
    public let file: String
    public let function: String?
    public let line: Int?
    /// Prefer a logical file identifier rather than a developer's absolute filesystem path.
    public init(file: String, function: String? = nil, line: Int? = nil) {
        self.file = file; self.function = function; self.line = line
    }
}

/// A caught/reported error, not evidence of a process crash. No stack is generated by the SDK.
public struct LogError: Sendable {
    public let type: String
    public let message: String?
    public let domain: String?
    public let code: String?
    public let stackTrace: String?
    public init(type: String, message: String? = nil, domain: String? = nil, code: String? = nil, stackTrace: String? = nil) {
        self.type = type; self.message = message; self.domain = domain; self.code = code; self.stackTrace = stackTrace
    }
}

/// Host-authorized details, independently classified from the log's summary message.
public struct LogDetails: Sendable {
    let arguments: [LogValue]
    let attributes: [LogField]
    let error: LogError?
    let callSite: LogCallSite?
    let isPrivate: Bool
    public static func publicValues(arguments: [LogValue] = [], attributes: [LogField] = [],
                                    error: LogError? = nil, callSite: LogCallSite? = nil) -> LogDetails {
        LogDetails(arguments: arguments, attributes: attributes, error: error, callSite: callSite, isPrivate: false)
    }
    public static let privateValues = LogDetails(arguments: [], attributes: [], error: nil, callSite: nil, isPrivate: true)
}

public enum LogDetailsState: String, Sendable { case available, omitted, limited, invalid, unsupported }

public struct LogDetailsReference: Sendable {
    public let state: LogDetailsState
    public let blobID: String?
    public let textByteCount: Int
    public static func restore(state: LogDetailsState, blobID: String?, textByteCount: Int) throws -> LogDetailsReference {
        guard (state == .available) == (blobID != nil), blobID.map(EvidenceValidation.id) ?? true,
              state == .available ? (1...65_536).contains(textByteCount) : textByteCount == 0 else { throw PersistenceError.invalidRecord }
        return LogDetailsReference(state: state, blobID: blobID, textByteCount: textByteCount)
    }
}

/// Encoded details are a separate, immutable payload, never part of a metadata snapshot.
public struct LogDetailsContent: Sendable {
    public let id: String
    public let text: String
    public let byteCount: Int
    public static func restore(id: String, text: String) throws -> LogDetailsContent {
        guard EvidenceValidation.id(id), !text.isEmpty, EvidenceValidation.text(text, limit: 65_536) else { throw PersistenceError.invalidRecord }
        return LogDetailsContent(id: id, text: text, byteCount: text.utf8.count)
    }
}

public enum LogDetailsLookup: Sendable { case available(LogDetailsContent), unavailable, busy }
public protocol LogDetailsSink: LogSink {
    /// Atomically admits the metadata and attempts bounded payload retention without waiting.
    func append(_ event: LogEvent, details: LogDetailsContent) throws -> LogWriteResult
}
public protocol LogDetailsHistory: LogHistory {
    func details(id: String) -> LogDetailsLookup
}

/// A bounded JSON writer for the explicit value model, not a general serializer or parser.
/// Stops before copying an oversized suffix; no getters, reflection, or intermediate object graph.
enum LogDetailsEncoding {
    enum Failure: Error { case limited, invalid }
    static func encode(_ input: LogDetails, limit: Int) throws -> String {
        guard input.arguments.count <= 32, input.attributes.count <= 64 else { throw Failure.limited }
        var fields = [LogField("arguments", .array(input.arguments)), LogField("attributes", .object(input.attributes))]
        if let error = input.error {
            guard !error.type.isEmpty else { throw Failure.invalid }
            var values = [LogField("type", .string(error.type))]
            if let value = error.message { values.append(LogField("message", .string(value))) }
            if let value = error.domain { values.append(LogField("domain", .string(value))) }
            if let value = error.code { values.append(LogField("code", .string(value))) }
            if let value = error.stackTrace { values.append(LogField("stackTrace", .string(value))) }
            fields.append(LogField("error", .object(values)))
        }
        if let site = input.callSite {
            guard !site.file.isEmpty, site.line.map({ (1...Int(Int32.max)).contains($0) }) ?? true else { throw Failure.invalid }
            var values = [LogField("file", .string(site.file))]
            if let value = site.function { values.append(LogField("function", .string(value))) }
            if let value = site.line { values.append(LogField("line", .integer(Int64(value)))) }
            fields.append(LogField("callSite", .object(values)))
        }
        var writer = Writer(limit: limit)
        try writer.value(.object(fields), depth: 0)
        return String(decoding: writer.bytes, as: UTF8.self)
    }
    private struct Writer {
        let limit: Int
        var bytes: [UInt8] = []
        var nodes = 0
        mutating func append(_ text: String) throws {
            for byte in text.utf8 {
                guard bytes.count < limit else { throw Failure.limited }
                bytes.append(byte)
            }
        }
        mutating func quoted(_ text: String, name: Bool = false) throws {
            try append("\"")
            var count = 0
            for scalar in text.unicodeScalars {
                let value = scalar.value
                count += value < 0x80 ? 1 : value < 0x800 ? 2 : value < 0x10000 ? 3 : 4
                guard count <= (name ? 256 : 16_384) else { throw Failure.limited }
                switch value {
                case 34: try append("\\\"")
                case 92: try append("\\\\")
                case 0..<32: try append(String(format: "\\u%04x", value))
                default: try append(String(scalar))
                }
            }
            try append("\"")
        }
        mutating func value(_ input: LogValue, depth: Int) throws {
            guard depth <= 8, nodes < 256 else { throw Failure.limited }; nodes += 1
            switch input {
            case .null: try append("null")
            case .boolean(let value): try append(value ? "true" : "false")
            case .integer(let value): try append(String(value))
            case .number(let value):
                guard value.isFinite else { throw Failure.invalid }; try append(String(value))
            case .string(let value): try quoted(value)
            case .array(let values):
                guard values.count <= 64 else { throw Failure.limited }; try append("[")
                for (index, item) in values.enumerated() { if index > 0 { try append(",") }; try self.value(item, depth: depth + 1) }
                try append("]")
            case .object(let fields):
                guard fields.count <= 64 else { throw Failure.limited }; try append("{")
                for (index, field) in fields.enumerated() {
                    if index > 0 { try append(",") }; try quoted(field.name, name: true); try append(":")
                    try value(field.value, depth: depth + 1)
                }
                try append("}")
            }
        }
    }
}
